    # 2. Load Voider22 comprehensive commentaries
    voider_map = {}
    if os.path.exists(VOIDER_PATH):
        with open(VOIDER_PATH, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    item = json.loads(line)
                    voider_map[(int(item["chapter"]), int(item["verse"]))] = item
        print(f"Loaded {len(voider_map)} comprehensive entries from {VOIDER_PATH}")

    # 3. Load translation cache
    cache = load_cache()

    # 4. Target languages for authentic translation
    # 22 Scheduled Indian Languages + English
    SUPPORTED_LANGUAGES = ["ta", "kn", "ml", "mr", "bn", "gu", "pa", "or", "as", "ur"]
    
    # Collect all English translations
    english_translations = [v.get("englishTranslation") or v.get("translation", "") for v in verses]

    # Pre-translate to top Indian languages
    translations_by_lang = {}
    for l_code in SUPPORTED_LANGUAGES:
        print(f"\nProcessing translations for: {l_code.upper()}...")
        translations_by_lang[l_code] = batch_translate_texts(english_translations, l_code, cache, batch_size=25)

    print("\nAll language translations retrieved and verified!")

    # 5. Process every verse: update Telugu, Hindi, Sanskrit, and Multilingual maps
    print("\nEnriching verse meanings, explanations, and commentaries...")
    
    updated_verses = []
    chapter_groups = {ch: [] for ch in range(1, 19)}

    for idx, v in enumerate(verses):
        ch = int(v["chapter"])
        vs = int(v["verse"])
        vid = f"{ch}-{vs}"

        voider_item = voider_map.get((ch, vs), {})

        # Extract & Clean Hindi Commentary (Swami Chinmayananda)
