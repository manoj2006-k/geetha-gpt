def load_cache():
    if os.path.exists(CACHE_FILE):
        try:
            with open(CACHE_FILE, 'r', encoding='utf-8') as f:
                return json.load(f)
        except Exception as e:
            print(f"Warning: Could not read cache: {e}")
    return {}

def save_cache(cache):
    try:
        with open(CACHE_FILE, 'w', encoding='utf-8') as f:
            json.dump(cache, f, ensure_ascii=False, indent=2)
    except Exception as e:
        print(f"Warning: Could not save cache: {e}")

def batch_translate_texts(texts, target_lang, cache, batch_size=20):
    """
    Translates a list of strings into target_lang using gtx endpoint with caching.
    """
    results = [None] * len(texts)
    missing_indices = []
    missing_texts = []

    lang_cache = cache.setdefault(target_lang, {})

    for idx, t in enumerate(texts):
        if not t:
            results[idx] = ""
            continue
        cleaned_key = t.strip()
        if cleaned_key in lang_cache:
            results[idx] = lang_cache[cleaned_key]
        else:
            missing_indices.append(idx)
            missing_texts.append(cleaned_key)

    if not missing_texts:
        return results

    print(f"  [{target_lang}] Translating {len(missing_texts)} uncached items in batches of {batch_size}...")

    for i in range(0, len(missing_texts), batch_size):
        chunk_indices = missing_indices[i : i + batch_size]
        chunk_texts = missing_texts[i : i + batch_size]

        combined = " \n###\n ".join(chunk_texts)
        url = (
            f"https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl={target_lang}&dt=t&q="
            + urllib.parse.quote(combined)
        )
        req = urllib.request.Request(
            url, headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"}
        )

        translated_parts = []
        for attempt in range(3):
            try:
                with urllib.request.urlopen(req, timeout=25) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
                    full_str = "".join([s[0] for s in data[0] if s and s[0]])
                    translated_parts = [p.strip() for p in full_str.split("###")]
                break
            except Exception as e:
                print(f"    Attempt {attempt+1} failed for {target_lang}: {e}")
                time.sleep(1.5)

        # In case separator split didn't match exactly
        if len(translated_parts) == len(chunk_texts):
            for orig_text, res_text, orig_idx in zip(chunk_texts, translated_parts, chunk_indices):
                lang_cache[orig_text] = res_text
                results[orig_idx] = res_text
        else:
            # Fallback to single translate for this small batch
            print(f"    Separator mismatch ({len(translated_parts)} != {len(chunk_texts)}), doing individual fallback...")
            for orig_text, orig_idx in zip(chunk_texts, chunk_indices):
                single_url = (
                    f"https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl={target_lang}&dt=t&q="
                    + urllib.parse.quote(orig_text)
                )
                try:
                    s_req = urllib.request.Request(single_url, headers={"User-Agent": "Mozilla/5.0"})
                    with urllib.request.urlopen(s_req, timeout=15) as s_resp:
                        s_data = json.loads(s_resp.read().decode("utf-8"))
                        s_str = "".join([s[0] for s in s_data[0] if s and s[0]]).strip()
                        lang_cache[orig_text] = s_str
                        results[orig_idx] = s_str
                except:
                    results[orig_idx] = orig_text
                time.sleep(0.1)

        time.sleep(0.2)

    save_cache(cache)
    return results


