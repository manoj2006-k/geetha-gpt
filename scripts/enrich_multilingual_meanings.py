def clean_telugu_text(t):
    if not t: return ""
    t = re.sub(r'^[।\s\d\.]+పలికెను\s*[-–:]?\s*', '', t)
    t = re.sub(r'^[।\s\d\.]+', '', t)
    return t.strip()

