def determine_speaker_and_context(ch, v, sanskrit_text):
    """Accurately identify speaker and dramatic context."""
    s = sanskrit_text.strip()
    if "धृतराष्ट्र उवाच" in s or (ch == 1 and v == 1):
        return "ధృతరాష్ట్రుడు", "ధృతరాష్ట్రుని సంభాషణ"
    if "सञ्जय उवाच" in s or "संजय उवाच" in s:
        return "సంజయుడు", "సంజయుని ప్రత్యక్ష రణరంగ వర్ణన"
    if "अर्जुन उवाच" in s:
        return "అర్జునుడు", "అర్జునుని సంశయ ప్రశ్నోపనిషత్తు"
    if "श्रीभगवानुवाच" in s or "श्री भगवानुवाच" in s:
        return "శ్రీ భగవానుడు", "శ్రీకృష్ణ పరమాత్మ దివ్యోపదేశం"
    
    # Narrative section fallbacks based on canonical Gita structure
    if ch == 1:
        if v <= 20: return "సంజయుడు", "రణరంగ సన్నద్ధత మరియు సైన్య వీక్షణ"
        elif 21 <= v <= 23: return "అర్జునుడు", "రథాన్ని నిలపవలసినదిగా అర్జునుని ప్రార్థన"
        elif 24 <= v <= 27: return "సంజయుడు", "బంధువులను చూసిన అర్జునుని స్థితి"
        elif 28 <= v <= 46: return "అర్జునుడు", "అర్జునుని తీవ్ర విషాద విలాపం"
        else: return "సంజయుడు", "గాండీవాన్ని విడిచి కూలబడిన అర్జునుడు"
    elif ch == 2:
        if v == 1 or v == 9 or v == 10: return "సంజయుడు", "అర్జునుని విచార స్థితి వర్ణన"
        elif 4 <= v <= 8 or v == 54: return "అర్జునుడు", "శరణాగతి మరియు జిజ్ఞాస"
        else: return "శ్రీ భగవానుడు", "సాంఖ్య మరియు కర్మయోగ బోధన"
    elif ch == 11:
        if 9 <= v <= 14 or v == 35 or v == 50: return "సంజయుడు", "దివ్య విశ్వరూప దర్శన వివరణ"
        elif (1 <= v <= 4) or (15 <= v <= 31) or (36 <= v <= 46) or v == 51: return "అర్జునుడు", "విశ్వరూప స్తోత్రము మరియు ప్రార్థన"
        else: return "శ్రీ భగవానుడు", "విశ్వరూప కాలతత్త్వ ప్రబోధము"
    elif ch == 18 and v >= 74:
        return "సంజయుడు", "సంవాద మాహాత్మ్య సంకీర్తన"
    
