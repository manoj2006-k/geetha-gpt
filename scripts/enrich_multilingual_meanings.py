        sankar_sc = ""
        if voider_item.get("sankar", {}).get("sc"):
            raw_sc = voider_item["sankar"]["sc"]
            if "did not comment on this sloka" not in raw_sc.lower():
                sankar_sc = re.sub(r'^[।\s\d\.]+', '', raw_sc).strip()
        if not sankar_sc and voider_item.get("raman", {}).get("sc"):
            raw_raman = voider_item["raman"]["sc"]
            sankar_sc = re.sub(r'^[।\s\d\.]+', '', raw_raman).strip()

