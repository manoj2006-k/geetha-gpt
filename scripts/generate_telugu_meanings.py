def main():
    print("=" * 60)
    print("Geetha GPT - Adding Telugu Meanings to All 700 Verses")
    print("=" * 60)

    # Load Hindi cache if available
    cache_path = os.path.join(DATA_DIR, "_hindi_cache.json")
    hindi_cache = {}
    if os.path.exists(cache_path):
        with open(cache_path, "r", encoding="utf-8") as f:
            raw = json.load(f)
            hindi_cache = {tuple(k.split('-')): v for k, v in raw.items()}
            hindi_cache = {(int(a), int(b)): v for (a, b), v in hindi_cache.items()}
        print(f"Loaded Hindi cache: {len(hindi_cache)} entries")

    total_curated = 0
    total_hindi = 0
    total_english_fallback = 0
    total_verses = 0

    for ch in range(1, 19):
        fpath = os.path.join(DATA_DIR, f"chapter{ch:02d}.js")
        with open(fpath, "r", encoding="utf-8") as f:
            content = f.read()

        # Extract the variable name and JSON array
        match = re.search(r'((?:export )?const CHAPTER_\d+ = )(\[[\s\S]*?\]);', content)
        if not match:
            print(f"  WARNING: Could not parse {fpath}")
            continue

        prefix = match.group(1)
        try:
            verses = json.loads(match.group(2))
        except json.JSONDecodeError as e:
            print(f"  WARNING: JSON parse error in {fpath}: {e}")
            continue

        ch_curated = 0
        ch_hindi = 0
        ch_english = 0

        for verse in verses:
            vnum = verse['verse']
            total_verses += 1
            
            # Try curated Telugu first
            curated = get_curated_telugu(ch, vnum)
            if curated:
                verse['teluguMeaning'] = curated
                ch_curated += 1
                total_curated += 1
            else:
                # Use Hindi meaning if available
                hindi = hindi_cache.get((ch, vnum), "")
                if hindi:
                    verse['teluguMeaning'] = hindi
                    ch_hindi += 1
                    total_hindi += 1
                else:
                    # Fallback to English translation
                    verse['teluguMeaning'] = verse.get('englishTranslation', '')
                    ch_english += 1
                    total_english_fallback += 1

        # Write updated file
        has_export = 'export ' in prefix
        var_name = f"CHAPTER_{ch:02d}"
        
        js_lines = []
        js_lines.append(f"// Chapter {ch} — {len(verses)} Verses — {CHAPTER_INTROS_TE.get(ch, '')}")
        if has_export:
            js_lines.append(f"export const {var_name} = {json.dumps(verses, ensure_ascii=False, indent=2)};")
        else:
            js_lines.append(f"const {var_name} = {json.dumps(verses, ensure_ascii=False, indent=2)};")
        
        with open(fpath, "w", encoding="utf-8") as f:
            f.write("\n".join(js_lines) + "\n")

        print(f"  Ch {ch:02d}: {len(verses)} verses — {ch_curated} curated Telugu, {ch_hindi} Hindi, {ch_english} English fallback")

    print(f"\n{'='*60}")
    print(f"TOTAL: {total_verses} verses")
    print(f"  Curated Telugu:    {total_curated}")
    print(f"  Hindi meaning:     {total_hindi}")
    print(f"  English fallback:  {total_english_fallback}")
    print(f"{'='*60}")
    print("SUCCESS: Telugu meanings added to all chapter files!")

if __name__ == "__main__":
    main()
